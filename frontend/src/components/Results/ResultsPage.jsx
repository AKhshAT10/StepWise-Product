import { useState } from 'react';
import StageTimeline from './StageTimeline';
import {
  CheckCircle2,
  AlertTriangle,
  Activity,
  Printer,
  Copy,
  RotateCcw,
  Sliders,
  FileText,
  Shield,
  Stethoscope,
  ChevronRight,
} from 'lucide-react';

export default function ResultsPage({ result, formData, onReset, onEdit }) {
  const [copied, setCopied] = useState(false);

  const { stage1, stage2, stage3, stage4, final_recommendation } = result;

  const isEligible = stage4?.eligibility_shortlist;
  const isAriaRisk = stage4?.aria_risk_flag;
  const isAmyloidNegative = stage4 && !stage4.eligible_amyloid;
  const stoppedAtStage1 = stage1 && !stage1.escalated;
  const stoppedAtStage2 = stage2 && !stage2.escalated;
  const stoppedAtStage3 = stage3 && !stage3.escalated;

  let outcomeType = 'non-escalated';
  let outcomeTitle = 'Assessment Complete — Routine Monitoring';
  let outcomeBadge = 'Low Risk Gate Hold';

  if (isEligible) {
    outcomeType = 'eligible';
    outcomeTitle = 'Eligible for Anti-Amyloid Therapy Shortlist';
    outcomeBadge = 'Candidate Shortlisted';
  } else if (isAriaRisk) {
    outcomeType = 'aria-risk';
    outcomeTitle = 'ARIA Safety Concern Detected';
    outcomeBadge = 'Safety Gate Hold';
  } else if (isAmyloidNegative) {
    outcomeType = 'negative-amyloid';
    outcomeTitle = 'Amyloid PET Negative — Excluded';
    outcomeBadge = 'Pathology Negative';
  } else if (stoppedAtStage1) {
    outcomeType = 'non-escalated';
    outcomeTitle = 'Cognitive Screening Negative — Low Risk';
    outcomeBadge = 'Stage 1 Non-Escalation';
  } else if (stoppedAtStage2) {
    outcomeType = 'non-escalated';
    outcomeTitle = 'Plasma Biomarkers Negative — Low Risk';
    outcomeBadge = 'Stage 2 Non-Escalation';
  } else if (stoppedAtStage3) {
    outcomeType = 'non-escalated';
    outcomeTitle = 'Structural MRI Non-Converter Profile';
    outcomeBadge = 'Stage 3 Non-Escalation';
  }

  const handleCopyReport = () => {
    const text = `PRECISION CARE MODEL — CLINICAL DECISION SUMMARY
Date: ${new Date().toLocaleDateString()}
Outcome: ${outcomeTitle}
Recommendation: ${final_recommendation}

STAGE CASCADE STATUS:
- Stage 1 (Cognitive/APOE): ${stage1 ? (stage1.escalated ? 'Escalated' : 'Gate Hold') : 'N/A'} (Prob: ${(stage1?.probability * 100).toFixed(1)}%, Cutoff: ${(stage1?.threshold * 100).toFixed(1)}%)
- Stage 2 (Blood Biomarkers): ${stage2 ? (stage2.escalated ? 'Escalated' : 'Gate Hold') : 'Not Reached'}
- Stage 3 (MRI Volumetrics): ${stage3 ? (stage3.escalated ? 'Escalated' : 'Gate Hold') : 'Not Reached'}
- Stage 4 (Eligibility/ARIA): ${stage4 ? (stage4.eligibility_shortlist ? 'Eligible Shortlist' : stage4.aria_risk_flag ? 'ARIA Safety Concern' : 'Ineligible') : 'Not Reached'}

Generated by PrecisionCare AD (ADNI Multi-Cohort ML Cascade v2.4)`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="results-container">
      {/* Hero Outcome Banner */}
      <div className={`outcome-hero-card ${outcomeType}`}>
        <div className="outcome-badge-row">
          <span
            className={`badge ${
              isEligible
                ? 'badge-emerald'
                : isAriaRisk
                ? 'badge-amber'
                : 'badge-cyan'
            }`}
          >
            {isEligible ? (
              <CheckCircle2 size={14} />
            ) : isAriaRisk ? (
              <AlertTriangle size={14} />
            ) : (
              <Activity size={14} />
            )}
            {outcomeBadge}
          </span>

          <span style={{ fontSize: '0.8rem', color: 'var(--text-muted)', fontFamily: 'var(--font-mono)' }}>
            Assessment ID: PCM-{Math.random().toString(36).substring(2, 8).toUpperCase()}
          </span>
        </div>

        <h1 className="outcome-hero-title">{outcomeTitle}</h1>
        <p className="outcome-hero-desc">{final_recommendation}</p>

        {/* Action Buttons */}
        <div style={{ display: 'flex', alignItems: 'center', flexWrap: 'wrap', gap: '0.75rem', marginTop: '0.5rem' }}>
          <button className="btn btn-secondary btn-sm" onClick={handlePrint}>
            <Printer size={15} />
            <span>Print Clinical Report</span>
          </button>
          <button className="btn btn-secondary btn-sm" onClick={handleCopyReport}>
            <Copy size={15} />
            <span>{copied ? 'Copied to Clipboard!' : 'Copy Summary'}</span>
          </button>
          {onEdit && (
            <button className="btn btn-secondary btn-sm" onClick={onEdit}>
              <Sliders size={15} />
              <span>Modify Inputs</span>
            </button>
          )}
          <button className="btn btn-primary btn-sm" onClick={onReset} style={{ marginLeft: 'auto' }}>
            <RotateCcw size={15} />
            <span>New Patient Assessment</span>
          </button>
        </div>
      </div>

      {/* Stage Cascade Breakdown Timeline */}
      <div style={{ display: 'flex', flexDirection: 'column', gap: '1rem' }}>
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>
          <h3>Stage-by-Stage Cascade Pathway</h3>
          <span style={{ fontSize: '0.8rem', color: 'var(--text-muted)' }}>
            Sequential gating based on ADNI-trained XGBoost thresholds
          </span>
        </div>
        <StageTimeline result={result} />
      </div>

      {/* Clinical Guidance & Recommended Next Actions */}
      <div className="clinical-actions-card">
        <h4 style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', color: 'var(--text-main)' }}>
          <Stethoscope size={18} style={{ color: 'var(--cyan-400)' }} />
          Clinical Action Recommendations
        </h4>

        <ul className="clinical-actions-list">
          {isEligible && (
            <>
              <li className="clinical-action-item">
                <ChevronRight size={16} style={{ color: 'var(--success)', flexShrink: 0, marginTop: 2 }} />
                <span>
                  <strong>Referral to Memory Clinic Specialist:</strong> Patient meets biomarker and neuroimaging criteria
                  for disease-modifying anti-amyloid therapy discussion.
                </span>
              </li>
              <li className="clinical-action-item">
                <ChevronRight size={16} style={{ color: 'var(--success)', flexShrink: 0, marginTop: 2 }} />
                <span>
                  <strong>Baseline ARIA Safety Protocol:</strong> Schedule MRI with T2*-GRE / SWI sequences prior to first infusion to establish microbleed baseline.
                </span>
              </li>
            </>
          )}

          {isAriaRisk && (
            <>
              <li className="clinical-action-item">
                <ChevronRight size={16} style={{ color: 'var(--warning)', flexShrink: 0, marginTop: 2 }} />
                <span>
                  <strong>Multidisciplinary Safety Review:</strong> Elevated ARIA risk noted (APOE ε4/ε4 homozygosity or microhemorrhage count ≥ 5).
                  Discuss alternative clinical trials or risk-benefit ratio with patient and family.
                </span>
              </li>
              <li className="clinical-action-item">
                <ChevronRight size={16} style={{ color: 'var(--warning)', flexShrink: 0, marginTop: 2 }} />
                <span>
                  <strong>Vascular Risk Factor Optimization:</strong> Intensify blood pressure and cerebrovascular management to mitigate further microhemorrhage accrual.
                </span>
              </li>
            </>
          )}

          {stoppedAtStage1 && (
            <li className="clinical-action-item">
              <ChevronRight size={16} style={{ color: 'var(--cyan-400)', flexShrink: 0, marginTop: 2 }} />
              <span>
                <strong>Routine Cognitive Surveillance:</strong> Demographics and MMSE profile do not warrant secondary biomarker
                investigation at this visit. Re-assess with MMSE or MoCA in 12 months.
              </span>
            </li>
          )}

          {stoppedAtStage2 && (
            <li className="clinical-action-item">
              <ChevronRight size={16} style={{ color: 'var(--cyan-400)', flexShrink: 0, marginTop: 2 }} />
              <span>
                <strong>Biomarker Discordance Follow-Up:</strong> Plasma p-tau217 and Aβ42/40 ratio are within normal limits despite initial screening flag.
                Secondary neuroimaging is deferred, avoiding unnecessary MRI/PET imaging costs.
              </span>
            </li>
          )}

          {stoppedAtStage3 && (
            <li className="clinical-action-item">
              <ChevronRight size={16} style={{ color: 'var(--cyan-400)', flexShrink: 0, marginTop: 2 }} />
              <span>
                <strong>Structural MRI Preservation:</strong> Hippocampal volumetrics and cortical thickness lack signature AD atrophy pattern.
                Continue annual cognitive tracking; confirmatory Amyloid PET scan avoided.
              </span>
            </li>
          )}
        </ul>
      </div>

      {/* Patient Input Audit Matrix */}
      {formData && (
        <div className="glass-card" style={{ padding: '1.75rem' }}>
          <div className="glass-card-header">
            <h4>Entered Clinical Biomarker Values</h4>
            <span className="badge badge-cyan" style={{ fontSize: '0.725rem' }}>
              Input Record
            </span>
          </div>

          <div
            style={{
              display: 'grid',
              gridTemplateColumns: 'repeat(auto-fit, minmax(180px, 1fr))',
              gap: '1rem',
              fontSize: '0.825rem',
            }}
          >
            <div>
              <span style={{ color: 'var(--text-muted)', display: 'block' }}>Age / Sex / Edu:</span>
              <strong className="font-mono">{formData.AGE} yrs / {formData.PTGENDER === 1 ? 'Female' : 'Male'} / {formData.PTEDUCAT} yrs</strong>
            </div>
            <div>
              <span style={{ color: 'var(--text-muted)', display: 'block' }}>MMSE / APOE ε4:</span>
              <strong className="font-mono">{formData.MMSCORE}/30 / {formData.APOE4} allele(s)</strong>
            </div>
            <div>
              <span style={{ color: 'var(--text-muted)', display: 'block' }}>Plasma p-tau217:</span>
              <strong className="font-mono">{formData.pT217_F} pg/mL</strong>
            </div>
            <div>
              <span style={{ color: 'var(--text-muted)', display: 'block' }}>Aβ42 / Aβ40 Ratio:</span>
              <strong className="font-mono">{formData.AB42_AB40_F}</strong>
            </div>
            <div>
              <span style={{ color: 'var(--text-muted)', display: 'block' }}>NfL / GFAP:</span>
              <strong className="font-mono">{formData.NfL_Q} / {formData.GFAP_Q}</strong>
            </div>
            <div>
              <span style={{ color: 'var(--text-muted)', display: 'block' }}>Hippocampus / Ventricle:</span>
              <strong className="font-mono">{formData.HIPPO_NORM} / {formData.VENTRICLE_NORM}</strong>
            </div>
            <div>
              <span style={{ color: 'var(--text-muted)', display: 'block' }}>Amyloid PET / Microbleeds:</span>
              <strong className="font-mono">{formData.AMYLOID_STATUS === 1 ? 'Positive' : 'Negative'} / {formData.MICROHEM_COUNT} count</strong>
            </div>
          </div>
        </div>
      )}

      {/* Model Output Details */}
      <div className="glass-card" style={{ padding: '1.75rem' }}>
        <div className="glass-card-header">
          <h4>Model Output Details</h4>
          <span className="badge badge-cyan" style={{ fontSize: '0.725rem' }}>
            Raw Predictions
          </span>
        </div>

        <div style={{ display: 'flex', flexDirection: 'column', gap: '1rem' }}>
          {/* Stage 1 Output */}
          {stage1 && (
            <div style={{ padding: '1rem', background: 'var(--bg-pill)', borderRadius: '0.5rem' }}>
              <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '0.5rem' }}>
                <strong style={{ fontSize: '0.875rem' }}>Stage 1 — Cognitive Screening</strong>
                <span className={`badge ${stage1.escalated ? 'badge-emerald' : 'badge-cyan'}`}>
                  {stage1.escalated ? 'Escalated' : 'Not Escalated'}
                </span>
              </div>
              <div style={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: '0.75rem', fontSize: '0.8rem' }}>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Probability</span>
                  <strong className="font-mono">{(stage1.probability * 100).toFixed(2)}%</strong>
                </div>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Threshold</span>
                  <strong className="font-mono">{(stage1.threshold * 100).toFixed(2)}%</strong>
                </div>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Decision</span>
                  <strong style={{ color: stage1.escalated ? 'var(--success)' : 'var(--text-cyan)' }}>
                    {stage1.probability >= stage1.threshold ? '≥ Threshold' : '< Threshold'}
                  </strong>
                </div>
              </div>
              <div style={{ marginTop: '0.5rem', fontSize: '0.75rem', color: 'var(--text-muted)' }}>
                Features: {stage1.features_used.join(', ')}
              </div>
            </div>
          )}

          {/* Stage 2 Output */}
          {stage2 && (
            <div style={{ padding: '1rem', background: 'var(--bg-pill)', borderRadius: '0.5rem' }}>
              <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '0.5rem' }}>
                <strong style={{ fontSize: '0.875rem' }}>Stage 2 — Blood Biomarkers</strong>
                <span className={`badge ${stage2.escalated ? 'badge-emerald' : 'badge-cyan'}`}>
                  {stage2.escalated ? 'Escalated' : 'Not Escalated'}
                </span>
              </div>
              <div style={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: '0.75rem', fontSize: '0.8rem' }}>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Probability</span>
                  <strong className="font-mono">{(stage2.probability * 100).toFixed(2)}%</strong>
                </div>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Threshold</span>
                  <strong className="font-mono">{(stage2.threshold * 100).toFixed(2)}%</strong>
                </div>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Decision</span>
                  <strong style={{ color: stage2.escalated ? 'var(--success)' : 'var(--text-cyan)' }}>
                    {stage2.probability >= stage2.threshold ? '≥ Threshold' : '< Threshold'}
                  </strong>
                </div>
              </div>
              <div style={{ marginTop: '0.5rem', fontSize: '0.75rem', color: 'var(--text-muted)' }}>
                Features: {stage2.features_used.join(', ')}
              </div>
            </div>
          )}

          {/* Stage 3 Output */}
          {stage3 && (
            <div style={{ padding: '1rem', background: 'var(--bg-pill)', borderRadius: '0.5rem' }}>
              <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '0.5rem' }}>
                <strong style={{ fontSize: '0.875rem' }}>Stage 3 — MRI Analysis</strong>
                <span className={`badge ${stage3.escalated ? 'badge-emerald' : 'badge-cyan'}`}>
                  {stage3.escalated ? 'Escalated' : 'Not Escalated'}
                </span>
              </div>
              <div style={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: '0.75rem', fontSize: '0.8rem' }}>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Probability</span>
                  <strong className="font-mono">{(stage3.probability * 100).toFixed(2)}%</strong>
                </div>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Threshold</span>
                  <strong className="font-mono">{(stage3.threshold * 100).toFixed(2)}%</strong>
                </div>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Decision</span>
                  <strong style={{ color: stage3.escalated ? 'var(--success)' : 'var(--text-cyan)' }}>
                    {stage3.probability >= stage3.threshold ? '≥ Threshold' : '< Threshold'}
                  </strong>
                </div>
              </div>
              <div style={{ marginTop: '0.5rem', fontSize: '0.75rem', color: 'var(--text-muted)' }}>
                Features: {stage3.features_used.join(', ')}
              </div>
            </div>
          )}

          {/* Stage 4 Output */}
          {stage4 && (
            <div style={{ padding: '1rem', background: 'var(--bg-pill)', borderRadius: '0.5rem' }}>
              <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '0.5rem' }}>
                <strong style={{ fontSize: '0.875rem' }}>Stage 4 — Treatment Eligibility</strong>
                <span className={`badge ${stage4.eligibility_shortlist ? 'badge-emerald' : 'badge-amber'}`}>
                  {stage4.eligibility_shortlist ? 'Eligible' : 'Not Eligible'}
                </span>
              </div>
              <div style={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: '0.75rem', fontSize: '0.8rem' }}>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Amyloid Positive</span>
                  <strong style={{ color: stage4.eligible_amyloid ? 'var(--success)' : 'var(--text-muted)' }}>
                    {stage4.eligible_amyloid ? 'Yes' : 'No'}
                  </strong>
                </div>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>ARIA Risk</span>
                  <strong style={{ color: stage4.aria_risk_flag ? 'var(--error)' : 'var(--success)' }}>
                    {stage4.aria_risk_flag ? 'Yes' : 'No'}
                  </strong>
                </div>
                <div>
                  <span style={{ color: 'var(--text-muted)', display: 'block' }}>Eligible</span>
                  <strong style={{ color: stage4.eligibility_shortlist ? 'var(--success)' : 'var(--error)' }}>
                    {stage4.eligibility_shortlist ? 'Yes' : 'No'}
                  </strong>
                </div>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
